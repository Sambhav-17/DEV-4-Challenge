import React, { useState, useEffect } from 'react';
import { StoryPromptOptions, MemoryRecord } from '../../types';
import { db } from '../../lib/storage/db';
import { soundscape } from '../../lib/audio/soundscape';
import { Sparkles, Copy, Check, Download, BookmarkPlus, RefreshCw, AlertCircle, Cpu, Sliders, ChevronDown, ChevronUp } from 'lucide-react';

interface StoryGeneratorProps {
  onStorySaved: (record: MemoryRecord) => void;
  onNavigateToAiLab: () => void;
}

export const StoryGenerator: React.FC<StoryGeneratorProps> = ({ onStorySaved, onNavigateToAiLab }) => {
  const [options, setOptions] = useState<StoryPromptOptions>({
    setting: 'abandoned observatory',
    mood: 'melancholic and mysterious',
    length: 'medium',
    inspirationType: 'object',
    inspirationText: 'A tarnished brass astrolabe found in a dead astronomer’s sea chest.',
    pov: 'first',
    pacing: 'slow-burn',
    recurringCharacter: '',
    endingStyle: 'bittersweet',
  });

  const [showAdvanced, setShowAdvanced] = useState(false);
  const [isGenerating, setIsGenerating] = useState(false);
  const [generatedStory, setGeneratedStory] = useState<string>('');
  const [storyTitle, setStoryTitle] = useState<string>('');
  const [modelSource, setModelSource] = useState<string>('');
  const [modelName, setModelName] = useState<string>('');
  const [errorMessage, setErrorMessage] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);
  const [saved, setSaved] = useState(false);

  // Default presets
  const SETTINGS = [
    'abandoned observatory',
    'forgotten library',
    'ancestral house in Michoacán',
    'deserted fog-bound train station',
    'decommissioned server room beneath the glacier',
    'candlelit cathedral ruins',
  ];

  const MOODS = [
    'melancholic and mysterious',
    'eerie and slow-burning',
    'nostalgic and bittersweet',
    'hopeful and gentle',
    'gothic and unsettling',
  ];

  const handleSummon = async () => {
    if (!options.inspirationText.trim()) {
      setErrorMessage('Please provide a memory, object, or custom inspiration prompt.');
      return;
    }

    setErrorMessage(null);
    setIsGenerating(true);
    setGeneratedStory('');
    setSaved(false);
    soundscape.playVeilBell();

    try {
      const res = await fetch('/api/ai/generate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(options),
      });

      const data = await res.json();

      if (res.ok && data.success) {
        setGeneratedStory(data.text);
        setModelSource(data.source);
        setModelName(data.model);
        // Create an atmospheric title
        const settingWord = options.setting.split(' ')[1] || 'Tale';
        setStoryTitle(`The Echo of ${settingWord.charAt(0).toUpperCase() + settingWord.slice(1)}`);
      } else {
        setErrorMessage(data.error || 'Failed to summon story from inference backend.');
      }
    } catch (err: any) {
      setErrorMessage('Network error: Could not reach the AFTERLIGHT backend service.');
    } finally {
      setIsGenerating(false);
    }
  };

  const handleSummonArchiveFallback = () => {
    setIsGenerating(true);
    setErrorMessage(null);
    soundscape.playVeilBell();
    setTimeout(() => {
      const settingWord = options.setting.split(' ')[1] || 'Shadow';
      const inspiration = options.inspirationText || 'a silver locket found beneath cold floorboards';
      const fallbackStory = `The silence of the ${options.setting} is broken only by the cold ticking of memory.\n\nIt was here that ${inspiration} first surfaced into the twilight. Shadows lengthened not with malice, but with the quiet dignity of things that once were loved. Across the quiet threshold, every breath of wind carried the cadence of footsteps that once walked with purpose; every wisp of mist held the shape of a promise that outlived the flesh.\n\nWhen night settles at last over the Veil, one discovers the gentle truth of the machine: ghosts are never monsters. They are human memories that loved this world too much to turn away.`;

      setStoryTitle(`The Echo of the ${settingWord.charAt(0).toUpperCase() + settingWord.slice(1)}`);
      setGeneratedStory(fallbackStory);
      setModelSource('archive_sanctuary');
      setModelName('Veil Memorial Vault (Autonomous Sanctuary)');
      setSaved(false);
      setIsGenerating(false);
    }, 700);
  };

  const handleCopy = () => {
    if (!generatedStory) return;
    navigator.clipboard.writeText(`${storyTitle}\n\n${generatedStory}`);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    if (!generatedStory) return;
    const content = `# ${storyTitle || 'A Story Beyond The Veil'}\n\n*Generated by ${modelName || 'AFTERLIGHT AI'}*\n\nSetting: ${options.setting}\nMood: ${options.mood}\n\n---\n\n${generatedStory}\n\n---\n*Preserved in AFTERLIGHT · Hacktoberfest 2026*`;
    const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${(storyTitle || 'afterlight_story').toLowerCase().replace(/\s+/g, '_')}.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const handleSaveToArchive = async () => {
    if (!generatedStory || saved) return;
    const newRecord: MemoryRecord = {
      id: `story-${Date.now()}`,
      title: storyTitle || `Ghost Story: ${options.setting}`,
      type: 'story',
      content: generatedStory,
      tags: ['Ghost Story', options.setting.split(' ')[0], options.mood.split(' ')[0]],
      isFavorite: true,
      authorName: modelName ? `AI Storyteller (${modelName})` : 'AFTERLIGHT Engine',
      meaningfulObjects: [options.inspirationText.slice(0, 40)],
      createdAt: Date.now(),
      updatedAt: Date.now(),
    };

    await db.saveMemory(newRecord);
    soundscape.playCandleChime();
    setSaved(true);
    onStorySaved(newRecord);
  };

  return (
    <section className="relative z-10 max-w-5xl mx-auto px-4 py-12">
      {/* Editorial Header */}
      <div className="text-center mb-10">
        <span className="text-xs uppercase tracking-[0.25em] text-[#D7AD63]">
          Section B · The Haunted Story Engine
        </span>
        <h2 className="mt-2 text-3xl md:text-5xl font-display font-semibold text-[#F3EBDD]">
          Summon Stories Beyond The Veil
        </h2>
        <p className="mt-3 text-sm md:text-base text-[#777985] max-w-xl mx-auto font-editorial italic">
          Weave lost memories, forgotten artifacts, and twilight atmospheres into literature powered by open-weight AI.
        </p>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-8 items-start">
        {/* Left Column: Story Configuration Controls (7 cols) */}
        <div className="lg:col-span-7 bg-[#101624]/90 border border-white/10 rounded-2xl p-6 md:p-8 shadow-2xl backdrop-blur-md">
          <div className="flex items-center justify-between pb-4 border-b border-white/10 mb-6">
            <h3 className="text-sm font-semibold uppercase tracking-wider text-[#F3EBDD] flex items-center gap-2">
              <Sparkles className="w-4 h-4 text-[#D7AD63]" />
              <span>Story Altar Configuration</span>
            </h3>
            <button
              onClick={() => setShowAdvanced(!showAdvanced)}
              className="text-xs text-[#91C7D8] hover:text-[#F3EBDD] flex items-center gap-1 cursor-pointer transition-colors"
            >
              <Sliders className="w-3.5 h-3.5" />
              <span>{showAdvanced ? 'Hide Advanced' : 'Advanced Nuance'}</span>
              {showAdvanced ? <ChevronUp className="w-3 h-3" /> : <ChevronDown className="w-3 h-3" />}
            </button>
          </div>

          <div className="space-y-5">
            {/* Setting */}
            <div>
              <label className="block text-xs uppercase tracking-wider text-[#777985] mb-2 font-mono">
                1. Atmospheric Setting
              </label>
              <select
                value={options.setting}
                onChange={(e) => setOptions({ ...options, setting: e.target.value })}
                className="w-full bg-[#08090D] border border-white/15 rounded-lg px-3.5 py-2.5 text-xs text-[#F3EBDD] focus:border-[#D7AD63] focus:outline-none transition-colors"
              >
                {SETTINGS.map((s) => (
                  <option key={s} value={s} className="bg-[#101624]">
                    {s.charAt(0).toUpperCase() + s.slice(1)}
                  </option>
                ))}
              </select>
            </div>

            {/* Mood */}
            <div>
              <label className="block text-xs uppercase tracking-wider text-[#777985] mb-2 font-mono">
                2. Supernatural Mood
              </label>
              <select
                value={options.mood}
                onChange={(e) => setOptions({ ...options, mood: e.target.value })}
                className="w-full bg-[#08090D] border border-white/15 rounded-lg px-3.5 py-2.5 text-xs text-[#F3EBDD] focus:border-[#D7AD63] focus:outline-none transition-colors"
              >
                {MOODS.map((m) => (
                  <option key={m} value={m} className="bg-[#101624]">
                    {m.charAt(0).toUpperCase() + m.slice(1)}
                  </option>
                ))}
              </select>
            </div>

            {/* Story Length Segmented Selector */}
            <div>
              <label className="block text-xs uppercase tracking-wider text-[#777985] mb-2 font-mono">
                3. Length
              </label>
              <div className="grid grid-cols-3 gap-2 bg-[#08090D] p-1 rounded-lg border border-white/10">
                {(['short', 'medium', 'long'] as const).map((len) => (
                  <button
                    key={len}
                    type="button"
                    onClick={() => setOptions({ ...options, length: len })}
                    className={`py-1.5 text-xs font-medium rounded-md capitalize transition-colors cursor-pointer ${
                      options.length === len
                        ? 'bg-[#D7AD63] text-[#08090D] font-semibold'
                        : 'text-[#777985] hover:text-[#F3EBDD]'
                    }`}
                  >
                    {len} {len === 'short' ? '· ~250w' : len === 'medium' ? '· ~400w' : '· ~600w'}
                  </button>
                ))}
              </div>
            </div>

            {/* Inspiration Type & Input */}
            <div>
              <div className="flex items-center justify-between mb-2">
                <label className="text-xs uppercase tracking-wider text-[#777985] font-mono">
                  4. The Spark of Remembrance
                </label>
                <div className="flex items-center gap-1 text-[11px] text-[#777985]">
                  {(['object', 'memory', 'event', 'custom'] as const).map((t) => (
                    <button
                      key={t}
                      type="button"
                      onClick={() => setOptions({ ...options, inspirationType: t })}
                      className={`px-2 py-0.5 rounded capitalize transition-colors cursor-pointer ${
                        options.inspirationType === t
                          ? 'bg-[#D7AD63]/20 text-[#D7AD63] font-semibold'
                          : 'hover:text-[#F3EBDD]'
                      }`}
                    >
                      {t}
                    </button>
                  ))}
                </div>
              </div>
              <textarea
                rows={3}
                value={options.inspirationText}
                onChange={(e) => setOptions({ ...options, inspirationText: e.target.value })}
                placeholder="Describe a grandfather's pocketwatch, a strange phone call in an empty house, or an old memory..."
                className="w-full bg-[#08090D] border border-white/15 rounded-lg p-3 text-xs text-[#F3EBDD] placeholder-[#777985] focus:border-[#D7AD63] focus:outline-none transition-colors resize-none"
              />
            </div>

            {/* Advanced Settings Drawer */}
            {showAdvanced && (
              <div className="pt-4 border-t border-white/10 space-y-4">
                <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
                  <div>
                    <label className="block text-[11px] uppercase tracking-wider text-[#777985] mb-1 font-mono">
                      Narrative POV
                    </label>
                    <select
                      value={options.pov}
                      onChange={(e) => setOptions({ ...options, pov: e.target.value as any })}
                      className="w-full bg-[#08090D] border border-white/10 rounded-md px-3 py-2 text-xs text-[#F3EBDD]"
                    >
                      <option value="first">First Person ("I walked into...")</option>
                      <option value="third">Third Person ("She reached for...")</option>
                    </select>
                  </div>

                  <div>
                    <label className="block text-[11px] uppercase tracking-wider text-[#777985] mb-1 font-mono">
                      Ending Resonance
                    </label>
                    <select
                      value={options.endingStyle}
                      onChange={(e) => setOptions({ ...options, endingStyle: e.target.value as any })}
                      className="w-full bg-[#08090D] border border-white/10 rounded-md px-3 py-2 text-xs text-[#F3EBDD]"
                    >
                      <option value="bittersweet">Bittersweet (Tender Ache)</option>
                      <option value="spectral-peace">Spectral Peace (Resolution)</option>
                      <option value="lingering-dread">Lingering Dread (Cold Wonder)</option>
                      <option value="open-ended">Open-Ended (Veil Shrouded)</option>
                    </select>
                  </div>
                </div>

                <div>
                  <label className="block text-[11px] uppercase tracking-wider text-[#777985] mb-1 font-mono">
                    Recurring Figure / Named Character (Optional)
                  </label>
                  <input
                    type="text"
                    value={options.recurringCharacter || ''}
                    onChange={(e) => setOptions({ ...options, recurringCharacter: e.target.value })}
                    placeholder="e.g. Mateo, Dr. Vance, The Keeper with silver glasses"
                    className="w-full bg-[#08090D] border border-white/10 rounded-md px-3 py-2 text-xs text-[#F3EBDD]"
                  />
                </div>
              </div>
            )}

            {/* Error Message */}
            {errorMessage && (
              <div className="p-3 bg-red-950/40 border border-red-800/40 rounded-lg text-xs text-red-200 flex items-start gap-2">
                <AlertCircle className="w-4 h-4 text-red-400 shrink-0 mt-0.5" />
                <div className="space-y-1">
                  <p>{errorMessage}</p>
                  <button
                    onClick={onNavigateToAiLab}
                    className="text-xs text-[#D7AD63] underline hover:text-[#e4be78] block font-mono cursor-pointer"
                  >
                    Open Open-Source AI Lab to inspect Ollama / model config →
                  </button>
                  <button
                    onClick={handleSummonArchiveFallback}
                    className="mt-2 inline-flex items-center gap-1.5 px-3 py-1.5 bg-[#D7AD63]/20 hover:bg-[#D7AD63]/30 text-[#D7AD63] border border-[#D7AD63]/40 rounded text-xs font-semibold cursor-pointer transition-colors"
                  >
                    <Sparkles className="w-3.5 h-3.5 text-[#D7AD63]" />
                    <span>Summon from Veil Archive Vault (Offline Fallback)</span>
                  </button>
                </div>
              </div>
            )}

            {/* Primary Action Button */}
            <button
              onClick={handleSummon}
              disabled={isGenerating}
              className={`w-full py-3.5 px-6 rounded-lg text-xs uppercase tracking-widest font-semibold flex items-center justify-center gap-2 transition-all cursor-pointer shadow-lg ${
                isGenerating
                  ? 'bg-[#1d2334] text-[#777985] cursor-not-allowed'
                  : 'bg-[#D7AD63] text-[#08090D] hover:bg-[#e4be78]'
              }`}
            >
              {isGenerating ? (
                <>
                  <RefreshCw className="w-4 h-4 animate-spin text-[#D7AD63]" />
                  <span>Summoning from the Veil...</span>
                </>
              ) : (
                <>
                  <Sparkles className="w-4 h-4" />
                  <span>Summon A Story</span>
                </>
              )}
            </button>
          </div>
        </div>

        {/* Right Column: Editorial Story Reader Parchment (5 cols) */}
        <div className="lg:col-span-5 bg-[#0e121b] border border-white/10 rounded-2xl p-6 md:p-8 flex flex-col justify-between min-h-[520px] shadow-2xl relative overflow-hidden">
          {/* Subtle background glow */}
          <div className="absolute top-0 right-0 w-64 h-64 bg-radial from-[#91C7D8]/10 to-transparent pointer-events-none" />

          {/* Active Story Content or Empty State */}
          <div className="relative z-10">
            {generatedStory ? (
              <div className="space-y-4">
                <div className="flex items-center justify-between pb-3 border-b border-white/10">
                  <span className="text-[11px] font-mono uppercase tracking-wider text-[#D7AD63]">
                    {modelName ? `Inscribed by ${modelName}` : 'Inscribed by Ghost Engine'}
                  </span>
                  <span className="text-[11px] text-[#777985] font-mono">
                    {modelSource === 'local_ollama' ? 'Local Ollama' : 'Demonstration Fallback'}
                  </span>
                </div>

                <h3 className="text-xl md:text-2xl font-display text-[#F3EBDD] tracking-wide">
                  {storyTitle}
                </h3>

                <div className="text-sm md:text-base text-[#F3EBDD]/90 font-editorial leading-relaxed whitespace-pre-wrap max-h-[380px] overflow-y-auto pr-2">
                  {generatedStory}
                </div>
              </div>
            ) : isGenerating ? (
              <div className="py-24 flex flex-col items-center justify-center text-center space-y-4">
                {/* Glowing spectral orb representation */}
                <div className="w-16 h-16 rounded-full bg-radial from-[#91C7D8] to-transparent animate-pulse flex items-center justify-center shadow-[0_0_30px_rgba(145,199,216,0.35)]">
                  <div className="w-6 h-6 rounded-full bg-[#F3EBDD]" />
                </div>
                <p className="text-sm font-display text-[#D7AD63] tracking-widest uppercase">
                  Listening across the Veil...
                </p>
                <p className="text-xs text-[#777985] max-w-xs font-editorial italic">
                  Calling the local open-weight neural model to inscribe your remembrance.
                </p>
              </div>
            ) : (
              <div className="py-20 flex flex-col items-center justify-center text-center space-y-4">
                <img
                  src="/src/assets/images/haunted_observatory_ruins_1793096629548.jpg"
                  alt="Abandoned Victorian Observatory"
                  className="w-full h-44 object-cover rounded-xl border border-white/10 opacity-70 mb-2"
                />
                <h4 className="text-base font-display text-[#D7AD63]">The Parchment Lies Open</h4>
                <p className="text-xs text-[#777985] max-w-xs font-editorial">
                  Configure your setting, choose an artifact or memory, and summon an original ghost story.
                </p>
              </div>
            )}
          </div>

          {/* Action Bar when story is present */}
          {generatedStory && (
            <div className="pt-4 border-t border-white/10 flex flex-wrap items-center justify-between gap-2 mt-6">
              <div className="flex items-center gap-1.5">
                {/* Copy */}
                <button
                  onClick={handleCopy}
                  className="p-2 text-[#777985] hover:text-[#F3EBDD] hover:bg-white/5 rounded-md transition-colors cursor-pointer"
                  title="Copy Story to Clipboard"
                >
                  {copied ? <Check className="w-4 h-4 text-emerald-400" /> : <Copy className="w-4 h-4" />}
                </button>

                {/* Download Markdown */}
                <button
                  onClick={handleDownload}
                  className="p-2 text-[#777985] hover:text-[#F3EBDD] hover:bg-white/5 rounded-md transition-colors cursor-pointer"
                  title="Download as Markdown"
                >
                  <Download className="w-4 h-4" />
                </button>

                {/* Regenerate */}
                <button
                  onClick={handleSummon}
                  disabled={isGenerating}
                  className="p-2 text-[#777985] hover:text-[#D7AD63] hover:bg-white/5 rounded-md transition-colors cursor-pointer"
                  title="Regenerate with Same Options"
                >
                  <RefreshCw className="w-4 h-4" />
                </button>
              </div>

              {/* Save to Archive */}
              <button
                onClick={handleSaveToArchive}
                disabled={saved}
                className={`flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium rounded-lg transition-colors cursor-pointer ${
                  saved
                    ? 'bg-emerald-950/60 text-emerald-300 border border-emerald-800/50'
                    : 'bg-[#D7AD63] text-[#08090D] hover:bg-[#e4be78]'
                }`}
              >
                {saved ? <Check className="w-3.5 h-3.5" /> : <BookmarkPlus className="w-3.5 h-3.5" />}
                <span>{saved ? 'Saved in Archive' : 'Save to Archive'}</span>
              </button>
            </div>
          )}
        </div>
      </div>
    </section>
  );
};
